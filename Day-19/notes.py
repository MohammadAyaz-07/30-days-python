''' syntax:
# open('filename',mode) 
# modes = 
"r"- read , opens a file for reading , returns error if file doesnt exist
"a" - Append , Opens a file for appending , creates a file if not exist
"w" - Write, Opens file for writing (overwrites the old), creates if no file
"x" - Create, Creates the specified file, returns error if no file
"t" - Text, Default value. Text mode
"b" - Binary (Binary mode eg: images)
'''

